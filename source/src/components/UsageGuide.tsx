export default function UsageGuide({
  tab,
  onClose,
}: {
  tab: number;
  onClose: () => void;
}) {
  const [index, setIndex] = useState(
    tab <= 1 ? 0 : tab === 2 ? 1 : tab === 3 ? 2 : tab === 4 ? 3 : 4,
  );
  const dialog = useRef<HTMLDialogElement>(null);
  useEffect(() => {
    const previous = document.activeElement as HTMLElement | null;
    const node = dialog.current;
    node?.showModal();
    return () => {
      node?.close();
      previous?.focus();
    };
  }, []);
  const guide = guides[index];
  return (
    <dialog
      className="guide-dialog"
      ref={dialog}
      aria-label="操作ガイド"
      onCancel={(e) => {
        e.preventDefault();
        onClose();
      }}
    >
      <section className="usage-guide" aria-label="使い方">
        <div className="guide-heading">
          <h2>使い方</h2>
          <button onClick={onClose}>使い方を閉じる</button>
        </div>
        <div className="guide-topics" role="group" aria-label="使い方の目的">
          {guides.map((g, i) => (
            <button
              key={g.name}
              aria-pressed={index === i}
              onClick={() => setIndex(i)}
            >
              {g.name}
            </button>
          ))}
        </div>
        <h3>{guide.name}</h3>
        <p className="guide-intro">{guide.intro}</p>
        <ol className="guide-steps">
          {guide.steps.map(([title, text]) => (
            <li key={title}>
              <strong>{title}</strong>
              <p>{text}</p>
            </li>
          ))}
        </ol>
        <p className="guide-note">{guide.note}</p>
      </section>
    </dialog>
  );
}
